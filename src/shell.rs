use std::path::Path;

use anyhow::{Result, bail};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Shell {
    Zsh,
    Bash,
}

impl Shell {
    pub fn parse(name: &str) -> Result<Self> {
        match name.to_ascii_lowercase().as_str() {
            "zsh" => Ok(Shell::Zsh),
            "bash" => Ok(Shell::Bash),
            other => bail!("暂不支持 shell：{other}（当前支持 zsh、bash）"),
        }
    }

    pub fn name(&self) -> &'static str {
        match self {
            Shell::Zsh => "zsh",
            Shell::Bash => "bash",
        }
    }
}

/// 单引号包裹，并把内部的 `'` 转义为 `'\''`。
fn sh_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', r"'\''"))
}

/// PATH 清理 + 激活。
///
/// 两个要点：
/// 1. 自包含——`activate` 的 eval 输出即使用户没跑过 `init` 也能工作。
/// 2. 运行时自探测 shell——不依赖 `$SHELL`，因为在脚本或非登录 shell 里它未必可靠。
///    zsh 用 `path` 数组，bash 用 `IFS=:` 切分，两者都不做通配展开。
const HELPERS: &str = r#"__brewpy_path_strip() {
  local target="$1" p out=""
  if [ -n "${ZSH_VERSION:-}" ]; then
    for p in "${path[@]}"; do
      case "$p" in
        "$target"|*/opt/python@*/libexec/bin) continue ;;
      esac
      out="${out:+$out:}$p"
    done
  else
    local -a parts
    local IFS=":"
    read -ra parts <<< "$PATH"
    for p in "${parts[@]}"; do
      case "$p" in
        "$target"|*/opt/python@*/libexec/bin) continue ;;
      esac
      out="${out:+$out:}$p"
    done
  fi
  PATH="$out"
  export PATH
}

__brewpy_activate() {
  local dir="$1"
  if [ -z "$dir" ]; then return 0; fi
  __brewpy_path_strip "$dir"
  if [ -z "$PATH" ]; then
    PATH="$dir"
  else
    PATH="$dir:$PATH"
  fi
  export PATH
  export BREWPY_ACTIVE_DIR="$dir"
  hash -r 2>/dev/null || true
}"#;

/// 把 `brewpy` 包装成 shell 函数：`use` / `reset` 这类需要修改当前会话环境的
/// 子命令走 eval，其余子命令直接转发给真正的可执行文件。
const WRAPPER: &str = r#"brewpy() {
  case "$1" in
    use|activate)
      shift
      local out
      out="$(command brewpy activate "$@")" || return $?
      if [ -n "$out" ]; then eval "$out"; fi
      ;;
    reset)
      local out
      out="$(command brewpy activate --reset)" || return $?
      if [ -n "$out" ]; then eval "$out"; fi
      ;;
    *)
      command brewpy "$@" ;;
  esac
}"#;

/// `eval "$(brewpy activate 3.12)"` 的输出。
pub fn activate_snippet(dir: &Path) -> String {
    format!(
        "{HELPERS}\n\n__brewpy_activate {}\n",
        sh_quote(&dir.to_string_lossy())
    )
}

/// `eval "$(brewpy reset)"` 的输出：移除所有 brewpy 注入过的路径。
pub fn reset_snippet() -> String {
    format!(
        "{HELPERS}\n\n__brewpy_path_strip \"\"\nunset BREWPY_ACTIVE_DIR\nhash -r 2>/dev/null || true\n"
    )
}

/// `eval "$(brewpy init zsh)"` 的输出：定义辅助函数与 `brewpy()` 包装，
/// 并在设置了默认版本时立即激活它。
pub fn init_snippet(shell: Shell, default_dir: Option<&Path>) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "# brewpy: Homebrew Python version switcher (generated by `brewpy init {}`)\n",
        shell.name()
    ));
    out.push_str(HELPERS);
    out.push_str("\n\n");
    out.push_str(WRAPPER);

    match default_dir {
        Some(dir) => {
            out.push_str("\n\n");
            out.push_str(&format!(
                "__brewpy_activate {}\n",
                sh_quote(&dir.to_string_lossy())
            ));
        }
        None => {
            out.push_str(
                "\n\n# 尚未设置默认版本，运行 `brewpy default 3.14` 之后新开的终端会自动生效\n",
            );
        }
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_shell() {
        assert_eq!(Shell::parse("zsh").unwrap(), Shell::Zsh);
        assert_eq!(Shell::parse("BASH").unwrap(), Shell::Bash);
        assert!(Shell::parse("fish").is_err());
    }

    #[test]
    fn quote_escapes_single_quotes() {
        assert_eq!(
            sh_quote("/opt/homebrew/opt/python@3.12"),
            "'/opt/homebrew/opt/python@3.12'"
        );
        assert_eq!(sh_quote("a'b"), "'a'\\''b'");
    }

    #[test]
    fn activate_snippet_is_self_contained() {
        let snippet = activate_snippet(Path::new("/opt/homebrew/opt/python@3.12/libexec/bin"));
        assert!(snippet.contains("__brewpy_activate()"));
        assert!(snippet.contains("__brewpy_activate '/opt/homebrew/opt/python@3.12/libexec/bin'"));
        assert!(snippet.contains("BREWPY_ACTIVE_DIR"));
    }

    #[test]
    fn reset_snippet_clears_marker() {
        let snippet = reset_snippet();
        assert!(snippet.contains("__brewpy_path_strip \"\""));
        assert!(snippet.contains("unset BREWPY_ACTIVE_DIR"));
    }

    #[test]
    fn init_without_default_has_no_activation() {
        let snippet = init_snippet(Shell::Zsh, None);
        assert!(snippet.contains("brewpy()"));
        assert!(!snippet.contains("__brewpy_activate '/"));
    }

    #[test]
    fn init_with_default_activates_it() {
        let snippet = init_snippet(Shell::Zsh, Some(Path::new("/opt/homebrew/opt/python@3.14/libexec/bin")));
        assert!(snippet.contains("brewpy()"));
        assert!(snippet.contains("__brewpy_activate '/opt/homebrew/opt/python@3.14/libexec/bin'"));
    }
}
